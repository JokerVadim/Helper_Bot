def get_emoji(item):
    item_lower = item.lower()
    for keyword, emoji in EMOJI_MAP.items():
        if keyword in item_lower:
            return emoji
    return "📌"

conn = sqlite3.connect("bot.db")
rows = conn.execute("SELECT id, item FROM list_items WHERE emoji IS NULL OR emoji = '📌'").fetchall()

print("Found %d items..." % len(rows))

for row in rows:
    item_id = row[0]
    item_text = row[1]
    emoji = get_emoji(item_text)
    conn.execute("UPDATE list_items SET emoji=? WHERE id=?", (emoji, item_id))
    print("  %s %s" % (emoji, item_text))

conn.commit()
conn.close()
